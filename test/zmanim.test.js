import assert from 'node:assert/strict';
import os from 'node:os';
import path from 'node:path';
process.env.DB_PATH = path.join(os.tmpdir(), `zm-${Date.now()}.db`);
process.env.DATA_DIR = os.tmpdir();
const z = await import('../src/zmanim.js');
const fri = z.dayInfo('2026-11-13');
assert.equal(fri.weekday, 'Friday'); assert.match(fri.candle_lighting, /^4:[12]\d PM$/); assert.ok(fri.sunset.endsWith('PM'));
const sat = z.dayInfo('2026-11-14');
assert.ok(sat.havdalah && sat.havdalah.endsWith('PM')); assert.ok(sat.holidays.some((h) => /Parashat/.test(h)), 'names the parsha');
const noon = (d) => new Date(d + 'Z');
assert.ok(z.inWindow(noon('2026-11-14T17:00:00'))); assert.ok(!z.inWindow(noon('2026-11-15T17:00:00'))); assert.ok(!z.inWindow(noon('2026-11-12T17:00:00')));
const rh = z.windows(noon('2026-09-11T12:00:00'), noon('2026-09-14T12:00:00'));
assert.equal(rh.length, 1); assert.ok(rh[0].end - rh[0].start > 48 * 3600000, 'Rosh Hashana weekend is one long window');
const issues = z.scheduleCheck({ depart_at: '2026-11-14T10:00', return_at: '2026-11-15T09:00', stops: [] });
assert.equal(issues.filter((i) => i.level === 'red').length, 1); assert.match(issues[0].text, /Shabbos or Yom Tov/);
const close = z.scheduleCheck({ depart_at: '2026-11-13T15:30', stops: [] }); assert.ok(close.some((i) => i.level === 'amber'));
assert.equal(z.scheduleCheck({ depart_at: '2026-11-17T10:00', stops: [] }).length, 0);
assert.ok(z.quietUntil(noon('2026-11-14T18:00:00')) > noon('2026-11-14T18:00:00')); assert.equal(z.quietUntil(noon('2026-11-16T18:00:00')), null);
console.log('Zmanim checks passed.');
